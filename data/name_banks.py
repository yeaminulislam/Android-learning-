def bn_to_latin(text):
    """বাংলা শব্দ → মোটামুটি উচ্চারণভিত্তিক লাতিন লিপি।"""
    out = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c in BN_DIGITS:
            out.append(BN_DIGITS[c])
        elif c in BN_CONS:
            base = BN_CONS[c]
            # হসন্ত (্) → স্বর ছাড়া ব্যঞ্জনবর্ণ
            if i + 1 < n and text[i + 1] == "্":
                out.append(base)
                i += 2
                continue
            # পরবর্তী স্বরচিহ্ন
            vowel = "a"
            if i + 1 < n and text[i + 1] in BN_VOWELS and text[i + 1] not in "অ":
                vowel = BN_VOWELS[text[i + 1]]
                i += 1
            elif i + 1 < n and text[i + 1] == "অ":
                i += 1
            out.append(base + vowel)
        elif c in BN_VOWELS:
            out.append(BN_VOWELS[c])
        elif c in " \t":
            out.append(" ")
        elif c in "-–—":
            out.append("-")
        i += 1
    s = "".join(out)
    # ছোটখাটো পরিষ্কার
    s = s.replace("aa", "a").replace("ii", "i").replace("uu", "u")
    s = "".join(ch for ch in s if ch.isalnum() or ch in " -")
    return " ".join(s.split()).strip()


